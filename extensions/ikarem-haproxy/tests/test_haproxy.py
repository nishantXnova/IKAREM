def test_cli_run_passes_flags_after_double_dash(tmp_path, monkeypatch, capsys):
    seen = {}

    def fake_run_command(path, haproxy=None, *extra):
        seen["extra"] = extra
        return ["haproxy", "-f", str(path), "-db", *extra]

    def fake_serve(cmd):
        seen["cmd"] = cmd
        return 0

    monkeypatch.setattr("ikarem_haproxy.cli.run_command", fake_run_command)
    monkeypatch.setattr("ikarem_haproxy.cli.serve", fake_serve)
    cfg_file = tmp_path / "haproxy.cfg"
    cfg_file.write_text("global\n", encoding="utf-8")

    assert cli_main(["run", "--config", str(cfg_file), "--", "-dM", "-V"]) == 0
    assert seen["extra"] == ("-dM", "-V")
    assert seen["cmd"][-3:] == ["-db", "-dM", "-V"]
    assert "starting HAProxy" in capsys.readouterr().out


def test_serve_returns_130_on_ctrl_c(monkeypatch):
    def boom(cmd):
        raise KeyboardInterrupt

    monkeypatch.setattr("ikarem_haproxy.subprocess.call", boom)
    assert serve(["haproxy", "-c", "-f", "x.cfg"]) == 130


