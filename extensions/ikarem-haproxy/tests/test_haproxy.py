"""ikarem-haproxy: the generated edge must match the app it fronts.

These tests pin the promises that make the config safe to ship: zones come
from the compiled blueprint map, the health check hits IKAREM's own probe,
client IPs are overwritten (not appended), TLS adds the redirect frontend,
and every failure names the fix. HAProxy itself is never required: the one
subprocess boundary is injected.
"""

from __future__ import annotations

import subprocess

import pytest
from ikarem_haproxy import (
    HAPROXY_REMEDY,
    build_edge,
    check_config,
    find_haproxy,
    render,
    run_command,
    serve,
    write_config,
)
from ikarem_haproxy.cli import main as cli_main

from ikarem import Blueprint, Depends, Ikarem, Schema, require_roles


class Item(Schema):
    name: str = "x"


def _app() -> Ikarem:
    app = Ikarem(enable_docs=False, auth_secret="haproxy-secret")

    @app.get("/api/status")
    async def status(req):
        return {"ok": True}

    @app.post("/api/items")
    async def create(req, item: Item):
        return {"ok": True}

    @app.get("/static/app.css")
    async def css(req):
        return {}

    @app.get("/")
    async def home(req):
        return {}

    @app.websocket("/ws/{room}")
    async def chat(ws):
        await ws.accept()

    billing = Blueprint("billing", url_prefix="/billing")

    @billing.get("/invoices")
    async def invoices(req, claims=Depends(require_roles("admin"))):
        return {"invoices": []}

    @billing.get("/invoices/{iid:int}")
    async def invoice(req, iid: int):
        return {"id": iid}

    app.register_blueprint(billing)
    return app


def _root_only_app() -> Ikarem:
    app = Ikarem(enable_docs=False, auth_secret="haproxy-secret")

    @app.get("/")
    async def home(req):
        return {}

    return app


def _cfg(**kwargs):
    return build_edge(_app(), source="app:app", **kwargs)


def _zone(cfg, label):
    return next(z for z in cfg.zones if z.label == label)


def test_zones_come_from_blueprints():
    cfg = _cfg()
    assert [z.label for z in cfg.zones] == ["billing", "app", "api"]

    billing = _zone(cfg, "billing")
    assert (billing.name, billing.prefixes, billing.routes, billing.auth) == (
        "zone_billing",
        ("/billing",),
        2,
        1,
    )

    ui = _zone(cfg, "app")
    assert ui.name == "zone_app"
    assert ui.prefixes == ("/static", "/ws") and ui.matches_root is True
    assert (ui.routes, ui.websockets) == (3, 1)

    api = _zone(cfg, "api")
    assert (api.prefixes, api.routes) == (("/api",), 2)
    assert cfg.routes == 7 and cfg.auth_routes == 1 and cfg.websockets == 1


def test_group_owning_root_is_the_default_backend():
    cfg = _cfg()
    assert cfg.default_zone == "zone_app"
    text = render(cfg)
    assert "    acl zone_app path_beg /static /ws" in text
    assert "    acl zone_app path /" in text
    assert "    default_backend zone_app" in text
    assert text.index("backend zone_billing") < text.index("backend zone_app")


def test_render_has_health_check_forwarding_and_tunnel():
    text = render(_cfg())
    assert "option httpchk GET /healthz" in text
    assert "http-check expect status 200" in text
    assert "server app1 127.0.0.1:8000 check" in text
    assert "timeout tunnel 1h" in text
    assert "option forwardfor if-none" in text
    assert "http-request set-header X-Forwarded-For %[src]" in text
    assert "http-request set-header X-Real-IP %[src]" in text
    assert "http-request set-header X-Forwarded-Proto http" in text


def test_render_is_deterministic_and_lf_only():
    cfg = _cfg()
    first, second = render(cfg), render(cfg)
    assert first == second
    assert first.endswith("\n") and "\r" not in first
    assert first.startswith("# Generated by ikarem-haproxy")


def test_multiple_upstreams_are_load_balanced():
    cfg = _cfg(upstream="127.0.0.1:8000,127.0.0.1:8001")
    assert cfg.upstreams == ("127.0.0.1:8000", "127.0.0.1:8001")
    text = render(cfg)
    assert "balance roundrobin" in text
    assert "server app1 127.0.0.1:8000 check" in text
    assert "server app2 127.0.0.1:8001 check" in text


def test_rate_limit_matches_ikarem_429_shape():
    text = render(_cfg(rate_limit=120))
    assert "stick-table type ip size 100k expire 30s store http_req_rate(10s)" in text
    assert "http-request track-sc0 src" in text
    assert "deny_status 429" in text
    assert "hdr Retry-After 10" in text
    assert '{"detail":"rate limit exceeded"}' in text
    assert "sc_http_req_rate(0) gt 120" in text
    # HAProxy's deny grammar wants the body before the headers.
    assert text.index('string \'{"detail"') < text.index("hdr Retry-After")
    assert "stick-table" not in render(_cfg(rate_limit=0))


def test_header_counts_routes_once():
    text = render(_cfg())
    assert "# 3 zones | 7 routes (1 WS) | 1 auth | 1 upstream" in text


def test_static_cache_is_an_edge_rule_not_a_backend_rule():
    text = render(_cfg(static_cache=3600))
    assert "acl edge_static path_beg /static" in text
    assert 'Cache-Control "public, max-age=3600, immutable" if edge_static' in text
    for block in text.split("\nbackend ")[1:]:
        assert "Cache-Control" not in block
    assert "edge_static" not in render(_cfg())


def test_static_cache_works_with_a_single_backend():
    cfg = _cfg(single_backend=True, static_cache=60)
    assert cfg.single_backend is True
    text = render(cfg)
    assert "acl edge_static path_beg /static" in text
    assert "acl zone_" not in text


def test_static_cache_warns_when_the_app_has_no_static_route():
    cfg = build_edge(_root_only_app(), static_cache=60)
    assert any("no /static route" in w for w in cfg.warnings)
    assert "# WARNING: static_cache is set" in render(cfg)


def test_plain_http_has_one_frontend_on_the_listen_address():
    text = render(_cfg(listen="0.0.0.0:9000"))
    assert "frontend ikarem_in" in text
    assert "bind 0.0.0.0:9000" in text
    assert "ikarem_http" not in text
    assert "Strict-Transport-Security" not in text


def test_tls_adds_redirect_frontend_and_hsts(tmp_path):
    pem = tmp_path / "site.pem"
    pem.write_text("dummy", encoding="utf-8")
    cfg = _cfg(tls_cert=pem, bind_https=":8443", bind_http=":8080")
    assert cfg.tls_cert == str(pem.resolve())
    text = render(cfg)
    assert "frontend ikarem_http" in text
    assert "bind :8080" in text
    assert "http-request redirect scheme https code 308" in text
    assert "frontend ikarem_https" in text
    assert "bind :8443 ssl crt" in text and "alpn h2,http/1.1" in text
    assert "ssl-default-bind-options ssl-min-ver TLSv1.2 no-tls-tickets" in text
    assert "Strict-Transport-Security" in text
    assert "set-header X-Forwarded-Proto https" in text
    assert "Strict-Transport-Security" not in render(_cfg(tls_cert=pem, hsts=False))


